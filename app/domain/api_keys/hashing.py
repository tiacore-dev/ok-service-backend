"""Hashing rules for API keys.

API keys are generated by the service as 48 random bytes
(``secrets.token_urlsafe(48)``, ~384 bits of entropy). For such
high-entropy secrets a single SHA-256 is sufficient: brute force or
dictionary attacks are infeasible, so a slow KDF (bcrypt/argon2) adds
nothing but latency. A deterministic digest also allows looking a key up
by an indexed unique column instead of scanning and verifying every row.

The digest must stay byte-for-byte compatible with the SQL expression used
by the migration that hashed legacy keys:
``encode(sha256(convert_to(token, 'UTF8')), 'hex')``.
"""

import hashlib
import secrets

API_KEY_HASH_LENGTH = 64
_API_KEY_RANDOM_BYTES = 48


def hash_api_key(raw_api_key: str) -> str:
    """Return the lowercase hex SHA-256 digest of a plaintext API key."""
    return hashlib.sha256(raw_api_key.encode("utf-8")).hexdigest()


def generate_raw_api_key() -> str:
    """Return a new random plaintext API key."""
    return secrets.token_urlsafe(_API_KEY_RANDOM_BYTES)
